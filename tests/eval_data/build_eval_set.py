"""Build or re-download the labelled evaluation set from Wikimedia Commons.

Every image has a recorded source page, author and license (see labels.csv).

  python tests/eval_data/build_eval_set.py           # download files listed in labels.csv (verifies SHA-1/SHA-256)
  python tests/eval_data/build_eval_set.py --select  # re-run the selection and rewrite labels.csv

Selection is deterministic and content-blind: candidates are filtered only by objective rules
(file type, size, EXIF camera tags / generator category, capture and upload date), then ordered by
a hash of the file title, and the first N per stratum are taken. Nobody looked at the images or the
model's scores when choosing them.

Real photos: Commons "Taken with <camera/phone>" categories (populated from EXIF), captured before
2022-06 and uploaded before 2023, i.e. before photorealistic generators were in wide use.
AI images: Commons "Images generated by <generator>" categories.

Derived variants (simulated WhatsApp compression, simulated screenshot, plain resize) are produced
locally with Pillow from real originals; they are labelled as simulations in labels.csv.

The images themselves are not committed to git (size, and CC BY-SA attribution requirements):
labels.csv carries attribution and checksums so the set can be rebuilt exactly.
"""
import argparse
import csv
import hashlib
import html
import io
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
IMG_DIR = HERE / "images"
LABELS = HERE / "labels.csv"
API = "https://commons.wikimedia.org/w/api.php"
UA = "DEI-eval-set/1.0 (college project; https://github.com/sruthikanova246-ux/IDP)"

# (stratum, candidate category names, how many). First category that exists is used.
REAL_SOURCES = [
    ("Canon EOS 5D Mark II (DSLR)", ["Taken with Canon EOS 5D Mark II"], 3),
    ("Nikon D7000 (DSLR)", ["Taken with Nikon D7000"], 3),
    ("Sony ILCE-7 (mirrorless)", ["Taken with Sony ILCE-7"], 3),
    ("Fujifilm X-T1 (mirrorless)", ["Taken with Fujifilm X-T1"], 3),
    ("Olympus E-M5 (mirrorless)", ["Taken with Olympus E-M5", "Taken with Olympus OM-D E-M5"], 3),
    ("Apple iPhone (phone)", ["Taken with iPhone 11 Pro", "Taken with iPhone 12 Pro", "Taken with iPhone 11"], 3),
    ("Samsung Galaxy (phone)", ["Taken with Samsung Galaxy S9", "Taken with Samsung Galaxy S8",
                                "Taken with Samsung Galaxy S7", "Taken with Samsung SM-G950F"], 3),
    ("Google Pixel (phone)", ["Taken with Google Pixel", "Taken with Google Pixel 2"], 3),
    ("Huawei P20 Pro (phone)", ["Taken with Huawei P20 Pro"], 3),
    ("Xiaomi (phone)", ["Taken with Xiaomi Redmi Note 7", "Taken with Xiaomi Mi A1", "Taken with Xiaomi Redmi Note 8 Pro",
                        "Taken with Xiaomi Mi 9"], 3),
]
AI_SOURCES = [
    ("Stable Diffusion", ["Images generated by Stable Diffusion"], 6),
    ("Midjourney", ["Images generated by Midjourney"], 6),
    ("DALL-E 3", ["Images generated by DALL-E 3"], 5),
    ("Bing Image Creator (DALL-E 3)", ["Images generated by Image Creator by Microsoft Bing"], 4),
    ("ChatGPT / GPT Image", ["Images generated by ChatGPT", "Images generated by GPT Image 1"], 5),
    ("Gemini / Nano Banana", ["Images generated by Gemini", "Images generated by Nano Banana"], 5),
    ("Flux", ["Images generated by Flux (text-to-image model)"], 4),
    ("Ideogram", ["Images generated by Ideogram"], 4),
    ("Adobe Firefly", ["Images generated by Adobe Firefly AI"], 3),
    ("Imagen", ["Images generated by Imagen"], 3),
]
EXCLUDE_TITLE = re.compile(r"pano|hdr|stitch|composite|collage|montage|comparison|grid|edited|retouch|"
                           r"crop|scan|diagram|logo|map|chart|text|meme|screenshot|animation", re.I)
VAL_FRACTION = 0.4
FIELDS = ["file", "label", "split", "stratum", "variant", "parent", "source_page", "download_url", "license",
          "author", "commons_sha1", "sha256", "width", "height", "camera_or_generator", "captured", "uploaded"]


def api(params, tries=6):
    params = {**params, "format": "json", "formatversion": "2"}
    url = API + "?" + urllib.parse.urlencode(params)
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60) as r:
                return json.loads(r.read())
        except (OSError, json.JSONDecodeError) as exc:
            wait = 5 * (attempt + 1)
            print(f"  API retry in {wait}s ({type(exc).__name__})")
            time.sleep(wait)
    raise RuntimeError("Commons API unavailable")


def download(url, tries=6):
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=120) as r:
                return r.read()
        except OSError as exc:
            wait = 10 * (attempt + 1)
            print(f"  download retry in {wait}s ({exc})")
            time.sleep(wait)
    raise RuntimeError(f"download failed: {url}")


def strip_html(text):
    return html.unescape(re.sub(r"<[^>]+>", "", text or "")).strip()[:120]


def category_files(category, max_pages=4):
    files, cont = [], {}
    for _ in range(max_pages):
        data = api({"action": "query", "generator": "categorymembers", "gcmtitle": "Category:" + category,
                    "gcmtype": "file", "gcmlimit": "50", "prop": "imageinfo",
                    "iiprop": "url|size|mime|sha1|timestamp|extmetadata|metadata", **cont})
        files += data.get("query", {}).get("pages", [])
        cont = data.get("continue")
        time.sleep(1.5)
        if not cont:
            break
    return files


def exif(info):
    return {m["name"]: m["value"] for m in (info.get("metadata") or []) if isinstance(m, dict) and "name" in m}


def title_key(title):
    return hashlib.sha1(title.encode("utf-8")).hexdigest()


def pick(stratum, categories, n, label):
    for cat in categories:
        pages = category_files(cat)
        if pages:
            break
        print(f"  category not found or empty: {cat}")
    else:
        print(f"!! no category for {stratum}")
        return []
    chosen = []
    for page in sorted(pages, key=lambda p: title_key(p["title"])):
        info = (page.get("imageinfo") or [{}])[0]
        title = page["title"]
        mime, size = info.get("mime"), info.get("size", 0)
        w, h = info.get("width", 0), info.get("height", 0)
        if EXCLUDE_TITLE.search(title) or min(w, h) < 512:
            continue
        ext = info.get("extmetadata", {})
        meta = exif(info)
        if label == "real":
            captured = str(meta.get("DateTimeOriginal") or "")
            if mime != "image/jpeg" or size > 12_000_000 or min(w, h) < 1200:
                continue
            if not (meta.get("Make") and meta.get("Model")) or not captured[:4].isdigit():
                continue
            if captured[:7].replace(":", "-") >= "2022-06" or info.get("timestamp", "9") >= "2023":
                continue
            source_of = f"{meta['Make']} {meta['Model']}".strip()
        else:
            if mime not in ("image/jpeg", "image/png", "image/webp") or size > 15_000_000:
                continue
            captured = ""
            source_of = stratum
        chosen.append({
            "label": label, "stratum": stratum, "variant": "original", "parent": "",
            "source_page": info.get("descriptionurl", ""), "download_url": info.get("url", ""),
            "license": strip_html(ext.get("LicenseShortName", {}).get("value")),
            "author": strip_html(ext.get("Artist", {}).get("value")),
            "commons_sha1": info.get("sha1", ""), "width": w, "height": h,
            "camera_or_generator": source_of, "captured": captured, "uploaded": info.get("timestamp", ""),
            "_title": title, "_ext": {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}[mime],
        })
        if len(chosen) == n:
            break
    print(f"  {stratum}: {len(chosen)}/{n} from '{cat}'")
    return chosen


def slug(text):
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")[:40]


# --- simulated real-world processing of real photos (deterministic) ---------------------------
def whatsapp_sim(img):
    """Approximates messaging-app re-compression: longest side 1600 px, JPEG q=60, metadata stripped."""
    img = img.convert("RGB")
    img.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=60, optimize=True)
    return buf.getvalue(), "jpg"


def screenshot_sim(img):
    """Approximates a phone screenshot of the photo: image fitted into a 1080x2340 PNG with UI bars."""
    img = img.convert("RGB")
    canvas = Image.new("RGB", (1080, 2340), (18, 18, 18))
    fitted = img.copy()
    fitted.thumbnail((1080, 1900), Image.Resampling.BICUBIC)
    canvas.paste(fitted, ((1080 - fitted.width) // 2, 220 + (1900 - fitted.height) // 2))
    draw = ImageDraw.Draw(canvas)
    draw.rectangle([0, 0, 1080, 90], fill=(0, 0, 0))
    draw.text((40, 30), "12:45", fill=(255, 255, 255))
    draw.rectangle([0, 2240, 1080, 2340], fill=(0, 0, 0))
    buf = io.BytesIO()
    canvas.save(buf, "PNG")
    return buf.getvalue(), "png"


def resized(img):
    """Plain downscale to 1024 px longest side, JPEG q=85 (typical web re-upload)."""
    img = img.convert("RGB")
    img.thumbnail((1024, 1024), Image.Resampling.BICUBIC)
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=85)
    return buf.getvalue(), "jpg"


DERIVATIONS = {"whatsapp_sim": whatsapp_sim, "screenshot_sim": screenshot_sim, "resized": resized}


def assign_splits(rows):
    by_stratum = {}
    for r in rows:
        by_stratum.setdefault((r["label"], r["stratum"]), []).append(r)
    for group in by_stratum.values():
        group.sort(key=lambda r: title_key(r["_title"]))
        n_val = max(1, round(len(group) * VAL_FRACTION))
        for i, r in enumerate(group):
            r["split"] = "val" if i < n_val else "test"


def select():
    rows = []
    for label, sources in (("real", REAL_SOURCES), ("ai", AI_SOURCES)):
        for stratum, cats, n in sources:
            print(f"Selecting {label}: {stratum}")
            rows += pick(stratum, cats, n, label)
    assign_splits(rows)
    for r in rows:
        r["file"] = f"{r['label']}/{slug(r['stratum'])}__{title_key(r['_title'])[:10]}.{r['_ext']}"
    originals = [{k: v for k, v in r.items() if not k.startswith("_")} for r in rows]
    return originals + make_derived(originals)


def make_derived(originals):
    """One simulated variant per real original. Kinds cycle within each split (ordered by file name),
    so validation and test both contain WhatsApp-style, screenshot and resized copies."""
    derived = []
    kinds = list(DERIVATIONS)
    for split in ("val", "test"):
        reals = sorted((r for r in originals if r["label"] == "real" and r["variant"] == "original"
                        and r["split"] == split), key=lambda r: r["file"])
        for i, r in enumerate(reals):
            kind = kinds[i % len(kinds)]
            stem = r["file"].rsplit(".", 1)[0]
            derived.append({**r, "variant": kind, "parent": r["file"],
                            "file": f"{stem}__{kind}.{'png' if kind == 'screenshot_sim' else 'jpg'}",
                            "commons_sha1": "", "sha256": "", "width": "", "height": ""})
    return derived


def fetch(rows):
    ok = True
    for r in rows:
        if r["variant"] != "original":
            continue
        path = IMG_DIR / r["file"]
        if path.exists() and (not r.get("sha256") or hashlib.sha256(path.read_bytes()).hexdigest() == r["sha256"]):
            continue
        print(f"Downloading {r['file']}  <- {r['source_page']}")
        data = download(r["download_url"])
        if r["commons_sha1"] and hashlib.sha1(data).hexdigest() != r["commons_sha1"]:
            print("  !! SHA-1 does not match Commons record; skipping")
            ok = False
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        time.sleep(1)
    for r in rows:
        if r["variant"] == "original":
            continue
        parent = IMG_DIR / r["parent"]
        if not parent.exists():
            ok = False
            continue
        with Image.open(parent) as src:
            data, _ = DERIVATIONS[r["variant"]](src)
        (IMG_DIR / r["file"]).write_bytes(data)
    for r in rows:
        path = IMG_DIR / r["file"]
        if not path.exists():
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if r.get("sha256") and digest != r["sha256"]:
            # derived files can differ across Pillow versions; originals must match exactly
            level = "!!" if r["variant"] == "original" else "note:"
            print(f"  {level} SHA-256 differs from labels.csv for {r['file']}")
            ok = ok and r["variant"] != "original"
        r["sha256"] = digest
        with Image.open(path) as im:
            r["width"], r["height"] = im.size
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--select", action="store_true", help="re-run selection and rewrite labels.csv")
    ap.add_argument("--rederive", action="store_true",
                    help="keep the originals in labels.csv and regenerate the simulated variants")
    args = ap.parse_args()
    if args.select or not LABELS.exists():
        rows = select()
    else:
        with open(LABELS, newline="", encoding="utf-8") as fh:
            rows = list(csv.DictReader(fh))
        if args.rederive:
            for old in IMG_DIR.glob("real/*__*_sim.*"):
                old.unlink()
            for old in IMG_DIR.glob("real/*__resized.*"):
                old.unlink()
            rows = [r for r in rows if r["variant"] == "original"]
            rows += make_derived(rows)
    ok = fetch(rows)
    with open(LABELS, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows({k: r.get(k, "") for k in FIELDS} for r in rows)
    counts = {}
    for r in rows:
        counts[(r["label"], r["split"])] = counts.get((r["label"], r["split"]), 0) + 1
    print("Done.", dict(sorted(counts.items())))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
